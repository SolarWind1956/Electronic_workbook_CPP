/*
	*****************************************************************************************************
	*
	*	void*
	*
	*****************************************************************************************************
	void* в C++ - это `универсальный` (или «общий») указатель, 
	который `может хранить💥💥💥 `адрес объекта` абсолютно `любого типа данных` 
	(int, double, char, пользовательские структуры и классы).
	
	Поскольку компилятор не знает, 
	на `объект` какого `размера` и `типа` указывает void*, 
	его называют «бестиповым указателем». 
	
	Из-за этого у него есть жесткие ограничения.
*/
/*
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	
	🛑 Два главных правила работы с void*

	1. 	Его `нельзя `разыменовать `напрямую`. 
	
		Нельзя получить значение по адресу *(ptr = void*), 
		так как компилятор не знает, 
		сколько байт нужно прочитать из памяти.
		
	2. 	С ним `нельзя использовать `указательную арифметику`. 
	
		Операции вроде ptr++ или ptr + 2 вызовут ошибку компиляции, 
		поскольку неизвестен размер шага (размер типа).
		
		Чтобы совершить любое действие с данными, 
		void* необходимо явно привести к конкретному типу.
*/
//	💻 Пример использования в коде
//	Для безопасного приведения типов в C++ используется static_cast: 

void first_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
    int 		number 		= 42;
    float 	pi_number 	= 3.14F;

    // 	1. 	void* может принять адрес любого типа без явного приведения
    void* 	genericPtr = &number; 
    
    // 	Ошибка! Так делать нельзя:
    // 	std::cout << *genericPtr; 

    // 	2. 	Чтобы прочитать данные, приводим к `int*`
    int* 	intPtr = static_cast<int*>(genericPtr);
    
	cout << "Число: " << *intPtr << '\n'; 		// 	Выведет 42

    // 	3. 	Перенаправляем тот же указатель на `float`
    genericPtr = &pi_number; 

    // 	Приводим к float* для чтения
    auto *  	floatPtr = static_cast<float*>(genericPtr);
    cout << "Pi: " << *floatPtr << '\n'; 		// 	Выведет 3.14
}
