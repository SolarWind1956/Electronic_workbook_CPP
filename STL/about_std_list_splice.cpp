/*
	*****************************************************************************************************
	*
	*	std::list::splice
	*
	*****************************************************************************************************
	Метод std::list::splice в C++ - 	это уникальная функция двусвязного списка (std::list), 
								которая переносит элементы 
								`из` одного списка 
								`в` другой списoк
								(или `меняет их `положение` 
								`внутри `того же` списка) 
								`без копирования и перемещения` самих `данных`.	
	
	Вместо `создания `новых объектов` 
	операция просто «перебрасывает» `внутренние указатели` `узлов` (nodes), 
	связывая их в новом месте. 
	
	Благодаря этому `существующие итераторы` и `ссылки на переносимые элементы` 
	остаются валидными, 
	меняется лишь то, какому контейнеру они теперь принадлежат.	
	
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	
	Варианты использования (перегрузки)

	Функция имеет `три` основных `сценария использования` 
	(для каждого с C++11 доступны варианты с `&` и `&&`
	для параметров списка):
	
	1. 	Перенос `всего списка целиком`:
	
		void splice	(	const_iterator 	pos
					, 	list& 			other
					);
		
		Все элементы из `other` перемещаются в текущий список `перед` позицией `pos`. 
		
		Список `other` становится `пустым`.
		
	2. 	Перенос одного конкретного элемента:
	
		void splice	(	const_iterator 	pos
					, 	list& 			other
					, 	const_iterator 	it
					);
	
		Переносит в текущий список `перед` позицией `pos` 
		из списка `other`  только элемент, на который указывает итератор `it`.
		
	3. 	Перенос диапазона элементов:
		
		void splice	(	const_iterator 	pos
					, 	list& 			other
					, 	const_iterator 	first
					, 	const_iterator 	last
					);
		
		Переносит в текущий список `перед` позицией `pos`  
		элементы из полуинтервала [first, last) списка `other`.
*/
/*
	--------------------------------------------------------------------------------------------------------------------------------------------------------
	
	Примеры кода


	1. 	Перенос элементов между разными списками
*/
void print_list(const std::string& name, const std::list<int>& list) 
{
    cout << name << ":";
	
    for (const auto& elem : list) {
		cout << " " << elem;
	}
    cout << "\n";
}
void first_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
	std::list<int> 	list1 = {1, 2, 3, 4};
    std::list<int> 	list2 = {10, 20, 30};

    // 	Вставляем ВЕСЬ `list2` в начало `list1`
    auto 			iter = list1.begin(); 
    list1.splice(iter, list2); 

    print_list("list1", list1); 	// 	Выведет: 10 20 30 1 2 3 4
    print_list("list2", list2); 	// 	Выведет: (пусто, элементы ушли)

    // 	Возвращаем один элемент (30) обратно в `list2`
    // 	Находим `30` в `list1`
    auto 	it_30 = std::ranges::find(list1.begin(), list1.end(), 30);
	
    list2.splice(list2.begin(), list1, it_30);

    print_list("list1 после возврата 30", list1); 	// 	Выведет: 10 20 1 2 3 4
    print_list("list2 после возврата 30", list2); 	// 	Выведет: 30
}
/*
	----------------------------------------------------------------------------------------------------------------------------------------------------------
	
	2. 	Перемещение элемента `внутри одного и того же` списка

	splice() часто используется для изменения порядка элементов 
	в рамках одного контейнера 
	(например, при реализации LRU-кэша, 
	когда нужно продвинуть элемент в начало списка как самый свежий):
*/
void second_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
	std::list<int> list = {1, 2, 3, 4, 5};

    // 	Переместим элемент '4' в самое начало списка
    auto it_4 = std::next(list.begin(), 3); 	// 	Итератор на четверку
    
    // 	Переносим элемент в начало `list` из этого же списка `list`
    list.splice(list.begin(), list, it_4); 

    // 	Выведет: 4 1 2 3 5
	for (const auto& elem : list) {
		cout << " " << elem;
	}
    cout << "\n";
}
/*
	----------------------------------------------------------------------------------------------------------------------------------------------------------
	
	Сложность операции (Big O)

	• 	O(1) (Константное время) 	- 	для переноса всего списка или одного элемента. 
									
									Операция выполняется мгновенно 
									вне зависимости от размера данных, 
									так как перелинковываются всего 2–4 указателя.
									
	• 	O(1) 					- 	при переносе диапазона [first, last) внутри того же самого списка.
	
	• 	O(N) (Линейное время) 	- 	при переносе диапазона [first, last) из другого списка. 
	
									Причина: 	Компилятору необходимо 
												физически подсчитать 
												количество переносимых элементов 
												(std::distance(first, last)), 
												чтобы корректно обновить 
												внутренний счетчик размера .size() 
												целевого списка.
*/
/*
	
	Важные ограничения и Undefined Behavior (UB)

	• 	Аллокаторы: 					Типы аллокаторов (Allocator) у обоих списков 
									должны полностью совпадать. 
								
									В противном случае поведение не определено.
								
	• 	Само-сплайсинг (Self-splicing): 	Нельзя передавать один и тот же список 
									в качестве `other` в первой перегрузке 
									(перенос всего списка в самого себя) - это вызовет UB.
	
	• 	Некорректный диапазон: 		При переносе диапазона [first, last) 
									итератор `pos` не должен находиться 
									`внутри `самого `переносимого диапазона`.
*/
/*
	std::list::splice 	- 	уникальный инструмент, 
						аналогов которому нет у других последовательных контейнеров 
						вроде std::vector или std::deque, 
						именно из-за `узловой структуры` 
						`связного списка`.
						
	Главное, что стоит всегда держать в голове:
	
	• 	Для `одного узла` или `всего списка` это всегда `моментальная операция` O(1).
	
	• 	Узлы `не пересоздаются в памяти`, 
		поэтому все `указатели` и `ссылки` на элементы 
		остаются живыми 
		(меняется только их «прописка» в контейнере).
*/
/*
	Перенос `части списка` (диапазона элементов) 
	реализуется с помощью третьей перегрузки std::list::splice.
	
	Её сигнатура выглядит так:
	
	void splice	(	const_iterator 	pos
				, 	list& 			other
				, 	const_iterator 	first
				, 	const_iterator 	last
				);
	
	Она перемещает элементы из списка `other` 
	из полуинтервала [first, last) (элемент first включается, а last - нет) 
	и вставляет их `перед` позицией `pos`.
	
	Ниже два практических примера: 
	
	-	перенос диапазона между двумя разными списками 
	и 
	-	перемещение блока элементов внутри одного списка.
	
	
	Пример 1: 	Перенос части элементов в `другой` список

	В этом сценарии мы берем «середину» одного списка 
	и врезаем её в другой спискок.
*/
void print(const std::string& label, const std::list<int>& list) 
{
    cout << label << ":";
    for (const auto& elem : list) {
		cout << " " << elem;
	}	
    cout << "\n";
}
void third_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
	std::list<int> 	from_list 	= {10, 20, 30, 40, 50};
    std::list<int> 	to_list   	= {1, 2, 3};

    // 	Выберем диапазон [20, 30, 40] из `from_list`.
    // 	`first` указывает на 20, last указывает на 50 (следующий за 40)
    auto 			first 		= std::next(from_list.begin(), 1); 	// 	указывает на 20
    auto 			last  		= std::next(from_list.begin(), 4); 	// 	указывает на 50

	// 	Вставим этот диапазон в `to_list` перед двойкой
    auto 			pos 			= std::next(to_list.begin(), 1); 		// 	указывает на 2

    // 	Выполняем `сплайсинг` диапазона
	to_list.splice	(	pos
					, 	from_list
					, 	first
					, 	last
					);

    print("to_list (результат)", to_list);     		// 	Выведет: 1 20 30 40 2 3
    print("from_list (что осталось)", from_list); 	// 	Выведет: 10 50
}
/*
	===================================================================
	
	Пример 2: 	Перемещение блока элементов `внутри `одного `списка`

	splice() позволяет легко сдвигать целые группы элементов 
	`внутри одного и того же` контейнера.
	
	❗❗❗💥💥💥
	Важное правило: 	
	
	целевая позиция `pos` 
	`не должна` находиться `внутри переносимого диапазона [first, last), 
	иначе произойдет неопределенное поведение (UB).
*/
void fourth_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';

	std::list<int> list = {1, 2, 3, 4, 5, 6};

    // 	Переместим блок {3, 4} в самый `конец списка`.
	
    auto first = std::next(list.begin(), 2); 	// 	указывает на 3
    auto last  = std::next(list.begin(), 4); 	// 	указывает на 5 (не включается)
    
    auto pos = list.end(); // вставляем в конец списка

    // 	Переносим элементы внутри списка `list`
    list.splice	(	pos
				, 	list
				, 	first
				, 	last
				);
	
	// 	Выведет: 1 2 5 6 3 4
	for (const auto& elem : list) {
		cout << " " << elem;
	}	
    cout << "\n";
}
