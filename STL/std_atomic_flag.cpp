/*
	**********************************************************************************************************************
	std::atomic_flag - это простейший атомарный логический тип данных в C++, 
	объявленный в заголовке <atomic>. 
	
	В отличие от всех остальных специализаций шаблона std::atomic (включая std::atomic<bool>), 
	он гарантированно свободен от блокировок (lock-free) на аппаратном уровне.
	
	У st`d::atomic_flag` отсутствуют стандартные операции чтения (load) и записи (store). 
	
	Вместо этого он предоставляет 
	низкоуровневые атомарные операции «проверить и установить» (test_and_set) и «очистить» (clear), 
	что делает его идеальным инструментом для сборки базовых примитивов синхронизации, 
	таких как spinlock (спин-лок).
	
	
	Основные методы класса

	• 	test_and_set(): 
	
		Атомарно устанавливает флаг в состояние `true` 
		и возвращает значение, которое было у флага `до вызова`.
		
	• 	clear(): Атомарно сбрасывает флаг в состояние `false`.
	
	• 	test() (начиная с C++20): 
		
		Атомарно возвращает `текущее значение флага` (без его изменения).
		
	• 	wait(), 
	
		notify_one(), 
		
		notify_all() (начиная с C++20): 
		
		Позволяют блокировать поток до тех пор, 
		пока `значение флага` не изменится,
		и поток не получит уведомление, 
		избавляя от необходимости 
		тратить процессорное время в «пустом» цикле.
	**********************************************************************************************************************
*/

