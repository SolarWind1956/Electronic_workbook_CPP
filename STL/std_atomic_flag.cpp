/*
	Здесь вызов функции clear() явно запрашивает `сброс флага` 
	с применением `семантики освобождения`, 
	а вызов функции test_and_set() использует `упорядочение доступа к памяти` 
	`по умолчанию` для `установки флага` и `извлечения старого значения`.
	
	Из первого объекта `std::atomic_flag` нельзя `путем копирования` (равно как и `перемещения`)
	создать еще один такой же объект, 
	и один `объект std::atomic_flag` нельзя `присвоить другому объекту`
	(ни `копированим`, ни `перемещением`). 
	
	Это `не конкретная `особенность `std::atomic_flag`, 
	а `общее правило` для `всех` `атомарных типов`. 
	
				Прямое `перемещение` (с помощью std::move) и `копирование` 
				объектов `std::atomic` ❗❗❗ запрещены стандартом C++.

				Главные причины:

				• 	Отсутствие конструкторов: 
					
					У класса std::atomic удалены конструктор копирования и конструктор перемещения 
					(copy/move constructor = delete).
					
				• 	Отсутствие операторов присваивания: 
				
					Операторы копирующего и перемещающего присваивания также явно удалены 
					(operator=).
				
				• 	Нарушение атомарности: 
				
					`Перемещение` подразумевает `перенос состояния` 
					(например, указателя или внутренних ресурсов) 
					от одного объекта к другому. 
					
					`Выполнить это `атомарно` 
					между `двумя разными объектами в памяти` 
					на уровне процессора невозможно. 
					
					`Атомарные типы` управляют своими данными 
					внутри конкретной ячейки памяти, 
					а не владеют динамическими ресурсами 
					вроде `std::string` или `std::vector`, 
					которые нужно «перехватывать».

	`Все операции` над `атомарными типами` определены как `атомарные`, 
	а `при присваивании` и `создании копии` 
	задействуются `два объекта`. 
	
	`Никакая операция` над `двумя различными объектами` 
	`не может` быть `атомарной`. 
	
	В случае с `созданием копии` или `копирующего присваивания` 
	`значение` сначала `должно быть считано` из одного объекта, 
	а затем `записано` в другой объект. 
	
	Это две разные операции над двумя разными объектами, 
	и их комбинация не может быть атомарной. 
	
	Поэтому 	такие операции запрещены.
	
	Ввиду `ограниченного набора функций` шаблон класса `std::atomic_flag` 
	идеально `подходит` для использования в `качестве `мьютекса` со `спин-блокировкой`. 
	
	`Изначально флаг сброшен`, и `мьютекс` `разблокирован`. 
	
	`Чтобы его `заблокировать`, 
	выполняется `цикл с вызовом функции` test_and_set(), 
	пока старое значение не будет равно `false`, 
	информируя, 
	что этот `поток установил` значение `флага` в `true`. 
	
	`Снятие блокировки с мьютекса` - это просто `сброс флага`. 
	Рассмотренная реализация показана в листинге 5.1.
*/
//	Листинг 5.1. 	Реализация мьютекса со спин-блокировкой с помощью std::atomic_flag
class spinlock_mutex
{
	std::atomic_flag 		atom_flg;
	
  public:
    spinlock_mutex() =  default;
    	
    void lock() {
		cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		/* 
			Поток, первый получивший доступ к этой функции, 
			установит флаг и будет выполнять свою работу.
			
			Для второго потока вход в эту функцию 
			приведет к многократно выполняющемуся пустому циклу,
			пока первый поток не сбросит флаг, вызвав компонентную функцию unlock()
		*/	
        while(atom_flg.test_and_set(std::memory_order_acquire))
		{
			;
		}
		/*
			При сброшенном флаге условие цикла ложно,
			(функция test_and_set() уставновит флаг в `true`,
			и возвратит его прежнее значение `false`),
			и цикл не выполнится ни разу;
			но сама проверка условия цикла и взведет флаг в `true`
			
			Другие потоки, входя в цикл при значении флага `true`, 
			повиснут на этом цикле, так как функция test_and_set() 
			будет и флаг устанавливать в `true`, 
			и возвращать его старое значение, тоже `true`,
			делая тем самым `истинное значение` условия цикла `while`
		*/		
    }
    void unlock()
    {
		cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		/*
			Флаг будет сброшен в `false`, при этом, какой-то из потоков, 
			висящих на цикле `while`, 
			сразу же выйдет из него, снова установив его в `true`, 
			захватив тем самым блокировку
		*/	
        atom_flg.clear(std::memory_order_release);	//	Запись `false` из регистра процессора в память,
												// 	в переменную `atom_flg`
    }
};
struct shared_resource	{
	static spinlock_mutex		spinlock_mtx;
	static std::vector<int> 	int_vector;
	static std::atomic<bool>	stop_flg;			//	Атомарная переменная как флаг останова
};	
std::vector<int> 		shared_resource::int_vector{};
std::atomic<bool>		shared_resource::stop_flg{false};
spinlock_mutex		shared_resource::spinlock_mtx{};

void shared_int_vector_reader(){
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
	
	while (!shared_resource::stop_flg.load(std::memory_order_relaxed)){
		
		shared_resource::spinlock_mtx.lock();
		{
			if (shared_resource::int_vector.empty())
			{
				std::this_thread::sleep_for(200ms);
				
				shared_resource::spinlock_mtx.unlock(); // НЕ ЗАБЫВАЕМ освободить перед continue!
				
				continue;
			}
			
			auto iter = shared_resource::int_vector.end();
			iter--;
			cout << "Выводим на печать последнее значение и удаляем его из вектора " << *iter << '\n';
			
			shared_resource::int_vector.pop_back();
		}
		shared_resource::spinlock_mtx.unlock();
		
		std::this_thread::sleep_for(200ms);
	}	
}
void shared_int_vector_writer(){
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		
	int count = 0;		
	
	while (!shared_resource::stop_flg.load(std::memory_order_relaxed)){
		
		shared_resource::spinlock_mtx.lock();
		{
			shared_resource::int_vector.push_back(count++);
		}
		shared_resource::spinlock_mtx.unlock();
		
		std::this_thread::sleep_for(200ms);
	}	
}
/*
	Для `stop_flg` используется порядок `std::memory_order_relaxed`. 
	
	Поскольку этот флаг служит исключительно `триггером` 
	для остановки и вокруг него нет операций, 
	требующих строгой синхронизации данных, 
	«расслабленный» порядок идеален - 
	он `не создает лишних барьеров памяти` и 
	работает максимально быстро.
*/
void second_example() 
{
	cerr << "------ I'm " <<  __PRETTY_FUNCTION__ << " in thread " 
        << std::this_thread::get_id() << '\n';
		
	shared_resource::stop_flg.store(false, std::memory_order_relaxed);
	
	std::thread 	writer_thrd(shared_int_vector_writer);
	
	std::thread 	reader_thrd(shared_int_vector_reader);
	
	std::this_thread::sleep_for(2000ms);
	
	// 	Атомарно сигнализируем о завершении
	shared_resource::stop_flg.store(true, std::memory_order_relaxed);
		
	writer_thrd.join();
	reader_thrd.join();
}
